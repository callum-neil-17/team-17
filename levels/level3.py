def _bartender_reaction_frame(scene: str, shift: int,
                              wave: int | None = None) -> str:
    rows = scene.strip("\n").splitlines()
    width = max(map(len, rows))
    canvas = [list(row.ljust(width)) for row in rows]

    def put(text: str, x: int, y: int) -> None:
        canvas[y][x:x + len(text)] = text

    if wave is not None:
        raised = BAR_FRAMES[1].strip("\n").splitlines()
        for y in range(7, 12):
            canvas[y][35:44] = raised[y][35:44].ljust(9)
        canvas[7][37:44] = " " * 7
        canvas[8][37:44] = " " * 7
        put("(o)", 39 + wave, 7)
        put("/ /", 38 + wave, 8)
    # A small headshake leaves the shelves, counter and stools untouched.
    for y in range(5, 9):
        canvas[y][27:37] = " " * 10
    put(".----.", 28 + shift, 5)
    put("|////|", 28 + shift, 6)
    put("|>  <|", 29 + shift, 7)
    put("| /\\ |", 29 + shift, 8)
    return "\n".join("".join(row) for row in canvas)


WRONG_FRAMES = [
    _bartender_reaction_frame(BAR_FRAMES[0], shift)
    for shift in (-1, 1, -1, 1, 0)
] + ["\n".join(row.ljust(68) for row in BAR_FRAMES[0].strip("\n").splitlines())]


def _bar_idle() -> list[str]:
    """Let the bartender blink and the sign flicker while you decide."""
    neutral = BAR_FRAMES[0].strip("\n")
    blink = neutral.replace("|o  o|", "|-  -|")
    flicker = neutral.replace("THE BAR", "TH  BAR")
    return ([neutral] * 6 + [blink] + [neutral] * 4 + [flicker, neutral, flicker]
            + [neutral] * 3 + [blink, neutral, blink])


IDLE_FRAMES = _bar_idle()


class Level3(Level):
    def __init__(self) -> None:
        super().__init__(
            number=3,
            title="Level 3",
            required_input=("\t","\x14"),
            art=BAR_FRAMES,
            description=fill(
                "You have entered a bar located on the planet cache. You currently do not have any money",
                width=70,
            ),
            wrong_frames=WRONG_FRAMES,
            prompt=fill(
                'Bartender: "Staying for a few drinks? '
                'Do you want to pay now or open a tab? ',
                width=70,
            ),
        )
        self.solved = False
        self.frame_delay = 0.2
        self.frame_delays[len(self.frames) - 1] = 0.6
        self.idle_frames = IDLE_FRAMES
        self.idle_frame_delay = 0.25
        self.wrong_guesses = 0

    def react_to_wrong_input(self, key: str | None, now: float | None = None) -> bool:
        ignored = (None, "", "q", "\x03", "\x04", "\x1a", "\x1c", "\x13", "\x11", "\x1b")
        if self.wrong_guesses < 5 and key not in ignored and key not in self.required_input:
            self.wrong_guesses += 1
            if self.wrong_guesses == 5:
                self.prompt = self.prompt.rstrip() + "\nThink about how you could open a tab?"
        # Each wrong guess counts even while the existing art reaction plays.
        return super().react_to_wrong_input(key, now=now)

    def check_input(self, key: str) -> bool:
        if not super().check_input(key):
            return False
        if self.solved:
            return True

        self.solved = True

        # Play the serving sequence, then advance without another key.
        return True
