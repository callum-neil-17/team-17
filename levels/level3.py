class Level3(Level):
    def __init__(self) -> None:
        super().__init__(
            number=3,
            title="Level 3",
            required_input=("\t",),
            art=BAR_FRAMES,
            description=fill(
                "You have entered a bar located on the planet cache. You currently do not have any money",
                width=70,
            ),
            prompt=fill(
                'Bartender: "Staying for a few drinks? '
                'Do you want to pay now or open a tab? ',
                width=70,
            ),
        )
        self.solved = False
        self.frame_delay = 0.2
        self.frame_delays[len(self.frames) - 1] = 0.6

    def check_input(self, key: str) -> bool:
        if not super().check_input(key):
            return False
        if self.solved:
            return True

        self.solved = True

        # Play the serving sequence, then advance without another key.
        return True
